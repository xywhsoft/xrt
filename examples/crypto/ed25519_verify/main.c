#include <stdio.h>
#include <xrt.h>



/*
 * 范例：crypto/ed25519_verify —— Ed25519 验签（RFC 8032 向量）
 * ----------------------------------------------------------------
 * 演示 API：
 *   xrtEd25519Verify   (公钥, 消息, 签名) → bool
 * 模块宏：XRT_MODULE_CRYPTO（ED25519 特性）
 * 编译（单头形态，Windows）：
 *   gcc -O1 -DXRT_MODULE_ALL -I single -include xrt.h impl.c ${BS}
 *       examples/crypto/ed25519_verify/main.c -lws2_32 -liphlpapi
 * 预期输出：
 *   verified: yes
 *
 * 公钥/签名来自 RFC 8032 §7.1 TEST 1（空消息）——
 *   标准向量命中即互操作证明：XRT 签的可被 OpenSSL 验，
 *   反之亦然。验签是公开操作，无密钥可清。
 */


/* 验证 RFC 8032 的空消息签名。 */
int main(void)
{
	static const uint8 Public[XRT_ED25519_PUBLIC_SIZE] = {
		0xD7, 0x5A, 0x98, 0x01, 0x82, 0xB1, 0x0A, 0xB7,
		0xD5, 0x4B, 0xFE, 0xD3, 0xC9, 0x64, 0x07, 0x3A,
		0x0E, 0xE1, 0x72, 0xF3, 0xDA, 0xA6, 0x23, 0x25,
		0xAF, 0x02, 0x1A, 0x68, 0xF7, 0x07, 0x51, 0x1A
	};
	static const uint8 Signature[XRT_ED25519_SIGNATURE_SIZE] = {
		0xE5, 0x56, 0x43, 0x00, 0xC3, 0x60, 0xAC, 0x72,
		0x90, 0x86, 0xE2, 0xCC, 0x80, 0x6E, 0x82, 0x8A,
		0x84, 0x87, 0x7F, 0x1E, 0xB8, 0xE5, 0xD9, 0x74,
		0xD8, 0x73, 0xE0, 0x65, 0x22, 0x49, 0x01, 0x55,
		0x5F, 0xB8, 0x82, 0x15, 0x90, 0xA3, 0x3B, 0xAC,
		0xC6, 0x1E, 0x39, 0x70, 0x1C, 0xF9, 0xB4, 0x6B,
		0xD2, 0x5B, 0xF5, 0xF0, 0x59, 0x5B, 0xBE, 0x24,
		0x65, 0x51, 0x41, 0x43, 0x8E, 0x7A, 0x10, 0x0B
	};
	bool bVerified = xrtEd25519Verify(Public, NULL, 0, Signature);

	printf("verified: %s\n", bVerified ? "yes" : "no");
	return bVerified ? 0 : 1;
}
