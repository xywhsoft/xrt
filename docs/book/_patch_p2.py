"""P2 批次 2 一次性扩写补丁（用后即删）。"""
import io

def patch(path, pairs):
    txt = io.open(path, encoding="utf-8").read()
    for old, new in pairs:
        assert old in txt, (path, old[:40])
        txt = txt.replace(old, new, 1)
    io.open(path, "w", encoding="utf-8", newline="\n").write(txt)
    print("patched", path)

