#include "../test.h"



/* 验证 RFC 7748 公钥和共享秘密向量。 */
static void testSshCurve25519Vector(void)
{
	static const unsigned char arrAlicePrivate[32] = {
		0x77u, 0x07u, 0x6du, 0x0au, 0x73u, 0x18u, 0xa5u, 0x7du,
		0x3cu, 0x16u, 0xc1u, 0x72u, 0x51u, 0xb2u, 0x66u, 0x45u,
		0xdfu, 0x4cu, 0x2fu, 0x87u, 0xebu, 0xc0u, 0x99u, 0x2au,
		0xb1u, 0x77u, 0xfbu, 0xa5u, 0x1du, 0xb9u, 0x2cu, 0x2au
	};
	static const unsigned char arrAlicePublic[32] = {
		0x85u, 0x20u, 0xf0u, 0x09u, 0x89u, 0x30u, 0xa7u, 0x54u,
		0x74u, 0x8bu, 0x7du, 0xdcu, 0xb4u, 0x3eu, 0xf7u, 0x5au,
		0x0du, 0xbfu, 0x3au, 0x0du, 0x26u, 0x38u, 0x1au, 0xf4u,
		0xebu, 0xa4u, 0xa9u, 0x8eu, 0xaau, 0x9bu, 0x4eu, 0x6au
	};
	static const unsigned char arrBobPublic[32] = {
		0xdeu, 0x9eu, 0xdbu, 0x7du, 0x7bu, 0x7du, 0xc1u, 0xb4u,
		0xd3u, 0x5bu, 0x61u, 0xc2u, 0xecu, 0xe4u, 0x35u, 0x37u,
		0x3fu, 0x83u, 0x43u, 0xc8u, 0x5bu, 0x78u, 0x67u, 0x4du,
		0xadu, 0xfcu, 0x7eu, 0x14u, 0x6fu, 0x88u, 0x2bu, 0x4fu
	};
	static const unsigned char arrExpectedShared[32] = {
		0x4au, 0x5du, 0x9du, 0x5bu, 0xa4u, 0xceu, 0x2du, 0xe1u,
		0x72u, 0x8eu, 0x3bu, 0xf4u, 0x80u, 0x35u, 0x0fu, 0x25u,
		0xe0u, 0x7eu, 0x21u, 0xc9u, 0x47u, 0xd1u, 0x9eu, 0x33u,
		0x76u, 0xf0u, 0x9bu, 0x3cu, 0x1eu, 0x16u, 0x17u, 0x42u
	};
	unsigned char arrPublic[32];
	unsigned char arrShared[32];

	testRequire((xrtSshCurve25519Public(
		arrAlicePrivate,
		arrPublic
	) == XSSH_OK) &&
		(memcmp(arrPublic, arrAlicePublic, sizeof(arrPublic)) == 0) &&
		(xrtSshCurve25519Shared(
			arrAlicePrivate,
			arrBobPublic,
			arrShared
		) == XSSH_OK) &&
		(memcmp(arrShared, arrExpectedShared, sizeof(arrShared)) == 0),
		"ssh curve25519 RFC vector mismatch");
}



/* 验证低阶公钥被拒绝且输出保持不变。 */
static void testSshCurve25519LowOrder(void)
{
	unsigned char arrPrivate[32] = { 1u };
	unsigned char arrPeer[32] = { 0u };
	unsigned char arrShared[32];
	unsigned char arrKeep[32];

	memset(arrShared, 0x5a, sizeof(arrShared));
	memcpy(arrKeep, arrShared, sizeof(arrKeep));
	testRequire((xrtSshCurve25519Shared(
		arrPrivate,
		arrPeer,
		arrShared
	) == XSSH_ERROR_PROTOCOL) &&
		(memcmp(arrShared, arrKeep, sizeof(arrShared)) == 0),
		"ssh curve25519 low-order rejection failed");
}



/* 运行 Curve25519 SSH 适配测试。 */
int main(void)
{
	testSshCurve25519Vector();
	testSshCurve25519LowOrder();
	return 0;
}
