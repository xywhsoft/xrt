#define XRT_IMPLEMENTATION
#include "../../single/xrt.h"



/* 单头文件只启用 SHA-256 时必须得到 RFC 6234 的 abc 摘要。 */
int main(void)
{
	static const uint8 arrExpected[XRT_SHA256_SIZE] = {
		0xBA, 0x78, 0x16, 0xBF, 0x8F, 0x01, 0xCF, 0xEA,
		0x41, 0x41, 0x40, 0xDE, 0x5D, 0xAE, 0x22, 0x23,
		0xB0, 0x03, 0x61, 0xA3, 0x96, 0x17, 0x7A, 0x9C,
		0xB4, 0x10, 0xFF, 0x61, 0xF2, 0x00, 0x15, 0xAD
	};
	uint8 arrDigest[XRT_SHA256_SIZE];

	return xrtSha256("abc", 3, arrDigest) &&
		xrtConstTimeEqual(arrDigest, arrExpected, sizeof(arrDigest)) ? 0 : 1;
}
