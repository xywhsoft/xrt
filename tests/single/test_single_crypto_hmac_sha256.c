#define XRT_IMPLEMENTATION
#include "../../single/xrt.h"



/* 验证单头文件 HMAC-SHA256 一次性入口。 */
int main(void)
{
	uint8 arrMac[XRT_SHA256_SIZE];
	static const uint8 arrExpected[] = {
		0x5B, 0xDC, 0xC1, 0x46, 0xBF, 0x60, 0x75, 0x4E,
		0x6A, 0x04, 0x24, 0x26, 0x08, 0x95, 0x75, 0xC7,
		0x5A, 0x00, 0x3F, 0x08, 0x9D, 0x27, 0x39, 0x83,
		0x9D, 0xEC, 0x58, 0xB9, 0x64, 0xEC, 0x38, 0x43
	};

	return (!xrtHmacSha256(
			"Jefe", 4, "what do ya want for nothing?", 28, arrMac
		) || !xrtConstTimeEqual(arrMac, arrExpected, sizeof(arrMac))) ? 1 : 0;
}
